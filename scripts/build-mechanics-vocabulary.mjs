import fs from 'node:fs';
import crypto from 'node:crypto';
const input='reports/mechanics-coverage/metadata-validation.json';
const bytes=fs.readFileSync(input),audit=JSON.parse(bytes);
const categories={'keyword-abilities':'keyword ability','keyword-actions':'keyword action','ability-words':'ability word'};
const labels=audit.results.filter(r=>r.status==='observed_exact_metadata').map(r=>({
  key:r.term.toLowerCase(),term:r.term,
  category:r.catalog_category_agrees&&r.listed_in_catalogs.length===1?categories[r.listed_in_catalogs[0]]:'other provider-reported term',
  sourceCategories:r.expected_catalogs,providerCategories:r.listed_in_catalogs,
})).sort((a,b)=>a.key<b.key?-1:a.key>b.key?1:0);
if(labels.length!==296||new Set(labels.map(r=>r.key)).size!==296)throw new Error('Audited vocabulary changed; requires review.');
const value={version:'2026-10-17',auditSha256:crypto.createHash('sha256').update(bytes).digest('hex'),
  manifestSha256:audit.manifest_sha256,bulkUpdatedAt:audit.bulk_updated_at,normalization:'lowercase exact; no other normalization',labels};
const output='// Generated by scripts/build-mechanics-vocabulary.mjs from the retained audit. No card memberships or definitions.\nexport default '+JSON.stringify(value,null,2)+';\n';
const file='public/mechanics-vocabulary.mjs';
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==output)throw new Error('Vocabulary differs from audited export.');}
else fs.writeFileSync(file,output);
console.log(`${labels.length} audited labels; ${Buffer.byteLength(output)} bytes; ${process.argv.includes('--check')?'unchanged':'exported'}.`);
